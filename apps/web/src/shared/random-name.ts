/** 修飾語と名詞を1つずつランダムに選んでくっつける。random は 0 以上 1 未満の値を返す関数 */
export function generateRandomName(random: () => number = Math.random) {
  const pick = <T>(words: readonly T[]) => words[Math.floor(random() * words.length)]
  return `${pick(MODIFIERS)}${pick(NOUNS)}`
}
